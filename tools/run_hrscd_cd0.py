IMG_MEAN=np.array([0.485,0.456,0.406],dtype=np.float32).reshape(3,1,1)
IMG_STD=np.array([0.229,0.224,0.225],dtype=np.float32).reshape(3,1,1)
ROLE_KEYS=("t1_image","t2_image","t1_label","t2_label","change_label")
LC_CLASSES=5
CHANGE_CLASSES=2
IGNORE=255


def sha256_file(path: Path) -> str:
    h=hashlib.sha256()
    with path.open("rb") as f:
        for buf in iter(lambda:f.read(1024*1024),b""):
            h.update(buf)
    return h.hexdigest()


def load_frozen_protocol(path: Path):
    proto=json.loads(path.read_text(encoding="utf-8"))
    if proto.get("status")!="FROZEN_PROJECT_DEFINED_SPLIT" or proto.get("protocol_version")!="hrscd_cd0_v1":
        raise ValueError("Refusing to train without the frozen HRSCD CD0 v1 protocol")
    manifest=Path(proto["manifest_path"])
    if not manifest.is_file() or sha256_file(manifest)!=proto["manifest_sha256"]:
        raise ValueError("Missing/changed manifest. Training blocked to protect protocol.")
    with manifest.open("r",encoding="utf-8-sig",newline="") as f:
        rows=list(csv.DictReader(f))
    if not rows or any(not all(row.get(k) for k in ("pair_id","split",*ROLE_KEYS)) for row in rows):
        raise ValueError("Empty or incomplete manifest")
    if len({r["pair_id"] for r in rows})!=len(rows):
        raise ValueError("Duplicate pair ID in manifest")
    if not {"train","val","test"} <= {r["split"] for r in rows}:
        raise ValueError("Manifest must contain train, val and test")
    root=Path(proto["dataset_root"])
    for row in rows:
        for role in ROLE_KEYS:
            path=(root/row[role]).resolve()
            if not path.is_relative_to(root.resolve()) or not path.is_file():
                raise ValueError(f"Missing/path traversal dataset raster: {path}")
    return proto,rows,root


def seed_everything(seed: int):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available(): torch.cuda.manual_seed_all(seed)


def windows(width: int,height: int,patch: int):
    for y in range(0,height,patch):
        for x in range(0,width,patch):
            yield x,y,min(patch,width-x),min(patch,height-y)


def read_crop(root: Path,row: dict,x:int,y:int,w:int,h:int,patch:int):
    import rasterio
    from rasterio.windows import Window
    with contextlib.ExitStack() as stack:
        ds={role:stack.enter_context(rasterio.open(root/row[role])) for role in ROLE_KEYS}
        win=Window(x,y,w,h)
        im1=ds["t1_image"].read([1,2,3],window=win)
        im2=ds["t2_image"].read([1,2,3],window=win)
        l1=ds["t1_label"].read(1,window=win)
        l2=ds["t2_label"].read(1,window=win)
        ch=ds["change_label"].read(1,window=win)
    if im1.dtype!=np.uint8 or im2.dtype!=np.uint8:
        raise ValueError("CD0 v1 requires 8-bit RGB images; revise and re-freeze protocol.")
    for name,l in (("T1 LC",l1),("T2 LC",l2)):
        bad=set(int(z) for z in np.unique(l))-set(range(6))
        if bad: raise ValueError(f"{name} contains unrecognized label values: {bad}")
    if set(int(z) for z in np.unique(ch))-{0,1}:
        raise ValueError("Change label is not 0/1; fix at protocol stage, not during training.")
    # Small edge windows are zero-padded ONLY for inference; padding is ignored.
    padded=(h!=patch or w!=patch)
    if padded:
        im1=np.pad(im1,((0,0),(0,patch-h),(0,patch-w)))
        im2=np.pad(im2,((0,0),(0,patch-h),(0,patch-w)))
        l1=np.pad(l1,((0,patch-h),(0,patch-w)),constant_values=0)
        l2=np.pad(l2,((0,patch-h),(0,patch-w)),constant_values=0)
        ch=np.pad(ch,((0,patch-h),(0,patch-w)),constant_values=IGNORE)
    return im1,im2,l1,l2,ch


def transform_crop(arrays,flip_h:bool,flip_v:bool):
    if flip_h: arrays=[np.flip(a,axis=-1) for a in arrays]
    if flip_v: arrays=[np.flip(a,axis=-2) for a in arrays]
    return [np.ascontiguousarray(a) for a in arrays]


def normalize_rgb(im: np.ndarray):
    return torch.from_numpy(np.ascontiguousarray((im.astype(np.float32)/255.-IMG_MEAN)/IMG_STD))


def tensor_sample(arrays):
    a,b,l1,l2,ch=arrays
    return {"t1":normalize_rgb(a),"t2":normalize_rgb(b),
            "lc1":torch.from_numpy(np.ascontiguousarray(l1.astype(np.int64))),
            "lc2":torch.from_numpy(np.ascontiguousarray(l2.astype(np.int64))),
            "change":torch.from_numpy(np.ascontiguousarray(ch.astype(np.int64)))}


class RandomPairCrops(Dataset):
    def __init__(self,rows,root,patch,seed,crops_per_pair=16):
        if not rows: raise ValueError("Empty training split")
        self.rows=list(rows);self.root=root;self.patch=patch;self.seed=seed
        self.crops_per_pair=crops_per_pair;self.epoch=0
        import rasterio
        self.sizes=[]
        for r in rows:
            with rasterio.open(root/r["t1_image"]) as ds:
                self.sizes.append((ds.width,ds.height))
                if min(ds.width,ds.height)<patch:
                    raise ValueError(f"Training image smaller than patch={patch}: {r['pair_id']}")
    def __len__(self): return len(self.rows)*self.crops_per_pair
    def __getitem__(self,idx):
        row_idx=idx % len(self.rows)
        row=self.rows[row_idx]
        width,height=self.sizes[row_idx]
        rng=np.random.default_rng(self.seed + self.epoch*10_000_003 + idx*97)
        # Half the time, try up to eight windows until one includes true change.
        # No deliberate deletion of empty-change patches.
        seek_positive=bool(rng.integers(0,2))
        x,y=0,0
        if seek_positive:
            import rasterio
            from rasterio.windows import Window
            with rasterio.open(self.root/row["change_label"]) as ds:
                for _ in range(8):
                    x=int(rng.integers(0,width-self.patch+1))
                    y=int(rng.integers(0,height-self.patch+1))
                    region=ds.read(1,window=Window(x,y,self.patch,self.patch))
                    if np.any(region==1):
                        break
        else:
            x=int(rng.integers(0,width-self.patch+1))
            y=int(rng.integers(0,height-self.patch+1))
        arrays=read_crop(self.root,row,x,y,self.patch,self.patch,self.patch)
        arrays=transform_crop(arrays,bool(rng.integers(0,2)),bool(rng.integers(0,2)))
        return tensor_sample(arrays)


class CD0Net(nn.Module):
    def __init__(self,pretrained:str|None="nvidia/mit-b2",width:int=96):
        super().__init__()
        try:
            from transformers import SegformerModel, SegformerConfig
        except ImportError as exc:
            raise RuntimeError("Please install transformers: python -m pip install transformers") from exc
        if pretrained:
            # Local model folder or HF ID; pretrained weights optional via --scratch.
            self.encoder=SegformerModel.from_pretrained(pretrained)
        else:
            cfg=SegformerConfig(num_encoder_blocks=4,depths=[3,4,6,3],
                hidden_sizes=[64,128,320,512],num_attention_heads=[1,2,5,8],
                sr_ratios=[8,4,2,1],patch_sizes=[7,3,3,3],strides=[4,2,2,2],
                mlp_ratios=[4,4,4,4],reshape_last_stage=True,num_channels=3)
            self.encoder=SegformerModel(cfg)
        sizes=list(self.encoder.config.hidden_sizes)
        if len(sizes)!=4:
            raise RuntimeError("Expected four MiT-B2 stages")
        self.lc_proj=nn.ModuleList(nn.Conv2d(c,width,1) for c in sizes)
        self.cd_proj=nn.ModuleList(nn.Conv2d(c,width,1) for c in sizes)
        self.semantic_head=nn.Sequential(
            nn.Conv2d(width*4,width,3,padding=1),nn.BatchNorm2d(width),
            nn.ReLU(inplace=True),nn.Conv2d(width,LC_CLASSES,1))
        self.change_head=nn.Sequential(
            nn.Conv2d(width*4,width,3,padding=1),nn.BatchNorm2d(width),
            nn.ReLU(inplace=True),nn.Conv2d(width,CHANGE_CLASSES,1))
    def extract(self,x):
        h=self.encoder(pixel_values=x,output_hidden_states=True,return_dict=True).hidden_states
        if len(h)<4: raise RuntimeError("Segformer did not return four hidden stages")
        feats=h[-4:]
        if any(t.ndim!=4 for t in feats):
            raise RuntimeError("Segformer hidden feature has unexpected shape; need reshape_last_stage=True")
        return feats
    def fuse(self,feats,projs):
        target=feats[0].shape[-2:]
        return torch.cat([F.interpolate(p(f),size=target,mode="bilinear",align_corners=False)
                          for f,p in zip(feats,projs)],dim=1)
    def forward(self,t1,t2):
        a=self.extract(t1); b=self.extract(t2)
        sem1=self.semantic_head(self.fuse(a,self.lc_proj))
        sem2=self.semantic_head(self.fuse(b,self.lc_proj))
        cd=self.change_head(self.fuse([torch.abs(u-v) for u,v in zip(a,b)],self.cd_proj))
        outsize=t1.shape[-2:]
        return (F.interpolate(cd,size=outsize,mode="bilinear",align_corners=False),
                F.interpolate(sem1,size=outsize,mode="bilinear",align_corners=False),
                F.interpolate(sem2,size=outsize,mode="bilinear",align_corners=False))


def map_landcover(gt:torch.Tensor):
    valid=(gt>=1)&(gt<=5)
    return torch.where(valid,gt-1,torch.full_like(gt,IGNORE))


def loss_cd0(logits,batch):
    cd,s1,s2=logits
    weights=cd.new_tensor([1.0,6.0]) # positive-change weighting; fixed protocol choice
    ch=batch["change"]
    valid=ch!=IGNORE
    if not bool(valid.any()):
        lc=cd.sum()*0
    else:
        lc=F.cross_entropy(cd,ch,weight=weights,ignore_index=IGNORE)
    def loss_seg(pred,gt):
        target=map_landcover(gt)
        return F.cross_entropy(pred,target,ignore_index=IGNORE) if bool((target!=IGNORE).any()) else pred.sum()*0
    s_loss=(loss_seg(s1,batch["lc1"])+loss_seg(s2,batch["lc2"]))*0.5
    return lc+s_loss, {"change":float(lc.detach()),"semantic":float(s_loss.detach())}


def confusion(pred,gt,n:int,valid=None):
    if valid is None: valid=(gt>=0)&(gt<n)
    else:valid=valid&(gt>=0)&(gt<n)
    p=pred[valid].reshape(-1).to(torch.int64).cpu()
    g=gt[valid].reshape(-1).to(torch.int64).cpu()
    return torch.bincount(g*n+p,minlength=n*n).reshape(n,n).numpy().astype(np.int64)


def metrics(conf_cd:np.ndarray,conf_lc1:np.ndarray,conf_lc2:np.ndarray):
    tn,fp,fn,tp=[int(x) for x in conf_cd.ravel()]
    def safe(n,d):return float(n/d) if d else 0.
    precision=safe(tp,tp+fp); recall=safe(tp,tp+fn)
    iou=safe(tp,tp+fp+fn)
    land={}
    for tag,c in (("t1",conf_lc1),("t2",conf_lc2)):
        ious=[]
        for cls in range(LC_CLASSES):
            x=int(c[cls,cls]); denom=int(c[cls,:].sum()+c[:,cls].sum()-x)
            ious.append(safe(x,denom) if denom else None)
        finite=[x for x in ious if x is not None]
        land[tag]={"iou_per_class":ious,"miou_present_classes":float(np.mean(finite)) if finite else None}
    return {"change_iou":iou,"change_f1":safe(2*tp,2*tp+fp+fn),
            "change_precision":precision,"change_recall":recall,
            "false_change_rate":safe(fp,tn+fp),
            "confusion_change":conf_cd.tolist(),
            "landcover":land,
            "confusion_t1":conf_lc1.tolist(),"confusion_t2":conf_lc2.tolist()}


@torch.no_grad()
def evaluate(model,rows,root,patch,device,amp,max_pairs:int=0,save_dir:Path|None=None):
    import rasterio
    from PIL import Image
    if max_pairs>0:
        rows=sorted(rows,key=lambda r:r["pair_id"])[:max_pairs]
    # Stream pair-by-pair; global confusion by actual pixels, not tile mean IoU.
    total_cd=np.zeros((2,2),dtype=np.int64)
    total_1=np.zeros((5,5),dtype=np.int64)
    total_2=np.zeros((5,5),dtype=np.int64)
    pair_metrics=[]
    model.eval()
    if save_dir: save_dir.mkdir(parents=True,exist_ok=True)
    for i,row in enumerate(rows,1):
        per_cd=np.zeros_like(total_cd); per1=np.zeros_like(total_1); per2=np.zeros_like(total_2)
        # Only count original valid label pixels in denominator.
        cov_gt1=np.zeros(5,dtype=np.int64);cov_gt2=np.zeros(5,dtype=np.int64)
        cov_pr1=np.zeros(5,dtype=np.int64);cov_pr2=np.zeros(5,dtype=np.int64)
        denom=0
        with rasterio.open(root/row["t1_image"]) as ds:
            width,height=ds.width,ds.height
        first_patch=True
        for x,y,w,h in windows(width,height,patch):
            arrays=read_crop(root,row,x,y,w,h,patch)
            batch=tensor_sample(arrays)
            a=batch["t1"][None].to(device)
            b=batch["t2"][None].to(device)
            with torch.autocast(device_type="cuda", enabled=(amp and device.type=="cuda")):
                pred=model(a,b)
            pd,pa,pb=[t.argmax(dim=1)[0,:h,:w].cpu() for t in pred]
            truth_cd=batch["change"][:h,:w]
            truth1=batch["lc1"][:h,:w]
            truth2=batch["lc2"][:h,:w]
            per_cd+=confusion(pd,truth_cd,2)
            per1+=confusion(pa,map_landcover(truth1),5)
            per2+=confusion(pb,map_landcover(truth2),5)
            paired=((truth1>=1)&(truth1<=5)&(truth2>=1)&(truth2<=5))
            # Combined paired-valid region: same area denominator in both years.
            denom+=int(paired.sum())
            for c in range(5):
                cov_gt1[c]+=int(((truth1==c+1)&paired).sum())
                cov_gt2[c]+=int(((truth2==c+1)&paired).sum())
                cov_pr1[c]+=int(((pa==c)&paired).sum())
                cov_pr2[c]+=int(((pb==c)&paired).sum())
            if save_dir and first_patch and i<=8:
                Image.fromarray((pd.numpy()*255).astype(np.uint8)).save(
                    save_dir/f"{row['pair_id'][:90]}_change_preview.png")
                first_patch=False
        total_cd+=per_cd;total_1+=per1;total_2+=per2
        result=metrics(per_cd,per1,per2)
        result["pair_id"]=row["pair_id"]
        result["paired_valid_pixels"]=denom
        result["coverage_by_class"]={}
        for c in range(5):
            n=c+1
            result["coverage_by_class"][str(n)]={
                "gt_t1":float(cov_gt1[c]/denom) if denom else None,
                "gt_t2":float(cov_gt2[c]/denom) if denom else None,
                "pred_t1":float(cov_pr1[c]/denom) if denom else None,
                "pred_t2":float(cov_pr2[c]/denom) if denom else None,
                "gt_delta":float((cov_gt2[c]-cov_gt1[c])/denom) if denom else None,
                "pred_delta":float((cov_pr2[c]-cov_pr1[c])/denom) if denom else None,
            }
        pair_metrics.append(result)
        print(f"[EVAL] pair {i}/{len(rows)} {row['pair_id']}: "
              f"change F1={result['change_f1']:.4f} false change={result['false_change_rate']:.4f}",
              flush=True)
    overall=metrics(total_cd,total_1,total_2)
    overall.update({"evaluated_pairs":len(rows),"full_split_evaluated":max_pairs==0 or len(rows)<max_pairs,
                    "pair_metrics":pair_metrics,
                    "warning":"Partial subset; NOT full validation" if max_pairs>0 else None})
    return overall


def memory_string():
    if not torch.cuda.is_available():return "GPU=not used"
    return "GPU allocated/reserved/peak={:.2f}/{:.2f}/{:.2f} GiB".format(
        torch.cuda.memory_allocated()/1024**3,
        torch.cuda.memory_reserved()/1024**3,
        torch.cuda.max_memory_allocated()/1024**3)


def iso_finish(seconds:float):
    return (dt.datetime.now().astimezone()+dt.timedelta(seconds=max(0,seconds))).isoformat(timespec="seconds")


def atomic_json(path:Path,obj):
    temp=path.with_suffix(path.suffix+".tmp")
    temp.write_text(json.dumps(obj,ensure_ascii=False,indent=2),encoding="utf-8")
    os.replace(temp,path)


def save_checkpoint(path,model,optimizer,epoch,best_f1,seed,protocol_sha):
    temp=path.with_suffix(".tmp")
    torch.save({"model":model.state_dict(),"optimizer":optimizer.state_dict(),
                "epoch":epoch,"best_val_f1":best_f1,"seed":seed,
                "protocol_sha256":protocol_sha},temp)
    os.replace(temp,path)


def main(argv=None):
    ap=argparse.ArgumentParser(description="HRSCD CD0 train/validate")
    ap.add_argument("--protocol",type=Path,required=True)
    ap.add_argument("--stage",choices=("train","validate"),default="train")
    ap.add_argument("--run-dir",type=Path,default=Path("outputs/hrscd_cd0/seed20260917"))
    ap.add_argument("--pretrained",default="nvidia/mit-b2",
                    help="HF MiT-B2 identifier or path; download needs network/cache")
    ap.add_argument("--scratch",action="store_true",help="Use randomly initialized MiT-B2")
    ap.add_argument("--seed",type=int,default=20260917)
    ap.add_argument("--epochs",type=int,default=30)
    ap.add_argument("--batch-size",type=int,default=2)
    ap.add_argument("--workers",type=int,default=2)
    ap.add_argument("--crops-per-pair",type=int,default=16)
    ap.add_argument("--lr",type=float,default=6e-5)
    ap.add_argument("--weight-decay",type=float,default=0.01)
    ap.add_argument("--patch",type=int,default=512)
    ap.add_argument("--eval-max-pairs",type=int,default=None,
                    help="train default 4 val pairs; standalone validate default all (0)")
    ap.add_argument("--eval-split",choices=("val","test"),default="val")
    ap.add_argument("--save-previews",action="store_true")
    ap.add_argument("--resume",action="store_true")
    ap.add_argument("--max-train-steps",type=int,default=0,
                    help="Dev smoke tests only; 0 means full epoch")
    args=ap.parse_args(argv)
    if min(args.batch_size,args.epochs,args.crops_per_pair,args.patch)<1 or args.workers<0:
        ap.error("positive epochs, patch, crops-per-pair, batch-size; workers >= 0")
    if args.eval_max_pairs is None: args.eval_max_pairs=4 if args.stage=="train" else 0
    if args.eval_max_pairs<0:ap.error("--eval-max-pairs must be nonnegative")
    proto,rows,root=load_frozen_protocol(args.protocol)
    protocol_sha=sha256_file(args.protocol)
    seed_everything(args.seed)
    run=args.run_dir.resolve()
    run.mkdir(parents=True,exist_ok=True)
    device=torch.device("cuda" if torch.cuda.is_available() else "cpu")
    amp=device.type=="cuda"
    print("[DATA]",root,proto["split_counts"])
    print("[MODEL] CD0 shared MiT-B2, GPU", device,flush=True)
    model=CD0Net(None if args.scratch else args.pretrained).to(device)
    opt=torch.optim.AdamW(model.parameters(),lr=args.lr,weight_decay=args.weight_decay)
    last=run/"last.ckpt"; best=run/"best.ckpt"
    start_epoch=1; best_f1=-1.0
    if args.resume or args.stage=="validate":
        ckpath=last if args.stage=="train" else best
        if not ckpath.is_file():raise FileNotFoundError(f"Checkpoint not found: {ckpath}")
        ck=torch.load(ckpath,map_location="cpu",weights_only=False)
        if ck.get("protocol_sha256")!=protocol_sha:
            raise ValueError("Checkpoint trained with a different frozen protocol")
        model.load_state_dict(ck["model"])
        best_f1=float(ck.get("best_val_f1",-1))
        if args.stage=="train":
            opt.load_state_dict(ck["optimizer"])
            start_epoch=int(ck["epoch"])+1
        print("[RESUMED]",ckpath,flush=True)
    if args.stage=="validate":
        splitrows=[r for r in rows if r["split"]==args.eval_split]
        results=evaluate(model,splitrows,root,args.patch,device,amp,args.eval_max_pairs,
                         run/"previews" if args.save_previews else None)
        results["split"]=args.eval_split
        results["checkpoint"]=str(best)
        atomic_json(run/f"{args.eval_split}_metrics.json",results)
        with (run/f"{args.eval_split}_per_pair.csv").open("w",encoding="utf-8-sig",newline="") as f:
            w=csv.DictWriter(f,fieldnames=["pair_id","change_iou","change_f1","false_change_rate",
                                            "paired_valid_pixels"])
            w.writeheader()
            w.writerows({k:r[k] for k in w.fieldnames} for r in results["pair_metrics"])
        print("[RESULT]",args.eval_split,"mIoU-change",results["change_iou"],
              "F1",results["change_f1"],"pairs",results["evaluated_pairs"])
        return 0

    trainrows=[r for r in rows if r["split"]=="train"]
    valrows=[r for r in rows if r["split"]=="val"]
    training=RandomPairCrops(trainrows,root,args.patch,args.seed,args.crops_per_pair)
    run_params={k:(str(v) if isinstance(v,Path) else v) for k,v in vars(args).items()}
    proto_snapshot={"base_protocol":proto,"base_protocol_sha256":protocol_sha,
                    "model_id":"CD0_shared_MiT_B2_AbsDiff",
                    "training_hyperparameters":run_params}
    snap=run/"protocol.json"
    if snap.exists():
        old=json.loads(snap.read_text(encoding="utf-8"))
        old_settings=old["training_hyperparameters"]
        # --resume may change, but core settings shouldn't.
        for key in ("seed","patch","pretrained","scratch","lr","weight_decay",
                    "batch_size","crops_per_pair"):
            if old_settings[key]!=run_params[key]:
                raise ValueError(f"Refusing to change training protocol: {key}")
        if old["base_protocol_sha256"]!=protocol_sha:
            raise ValueError("Frozen dataset protocol changed during run")
    else:
        atomic_json(snap,proto_snapshot)
    log=run/"train_log.jsonl"
    start=time.monotonic()
    for epoch in range(start_epoch,args.epochs+1):
        training.epoch=epoch
        loader=DataLoader(training,batch_size=args.batch_size,shuffle=True,
                          num_workers=args.workers,pin_memory=(device.type=="cuda"),
                          persistent_workers=False)
        model.train()
        values=[]
        total_steps=len(loader) if args.max_train_steps==0 else min(len(loader),args.max_train_steps)
        for step,batch in enumerate(loader,1):
            if step>total_steps: break
            for k in batch:batch[k]=batch[k].to(device,non_blocking=True)
            opt.zero_grad(set_to_none=True)
            with torch.autocast(device_type="cuda",enabled=amp):
                logits=model(batch["t1"],batch["t2"])
                loss,parts=loss_cd0(logits,batch)
            if not torch.isfinite(loss):
                raise RuntimeError(f"NaN/Inf loss at epoch {epoch} step {step}")
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(),1.0)
            opt.step()
            values.append(float(loss.detach()))
            if step==1 or step%10==0 or step==total_steps:
                elapsed=time.monotonic()-start
                done=(epoch-1)*total_steps+step
                target=max(1,args.epochs*total_steps)
                eta=(elapsed/done)*(target-done) if done else 0
                print(f"[TRAIN] epoch {epoch}/{args.epochs} step {step}/{total_steps} "
                      f"loss={values[-1]:.4f} elapsed={elapsed/60:.1f}m "
                      f"ETA={eta/60:.1f}m finish~{iso_finish(eta)} {memory_string()}",flush=True)
        if not values:raise RuntimeError("No training updates")
        val=evaluate(model,valrows,root,args.patch,device,amp,args.eval_max_pairs)
        f1=val["change_f1"]
        selected=f1>best_f1
        if selected: best_f1=f1
        save_checkpoint(last,model,opt,epoch,best_f1,args.seed,protocol_sha)
        if selected: save_checkpoint(best,model,opt,epoch,best_f1,args.seed,protocol_sha)
        entry={"epoch":epoch,"loss_mean":float(np.mean(values)),"val_change_f1":f1,
               "val_change_iou":val["change_iou"],"val_pairs":val["evaluated_pairs"],
               "val_subset_only":args.eval_max_pairs>0,"checkpoint_best":selected,
               "elapsed_sec":round(time.monotonic()-start,2),"gpu_memory":memory_string()}
        with log.open("a",encoding="utf-8") as stream:
            stream.write(json.dumps(entry,ensure_ascii=False)+"\n")
        atomic_json(run/"progress.json",{"epoch":epoch,"total_epochs":args.epochs,
                                          "last_epoch":entry,"best_val_change_f1":best_f1})
        atomic_json(run/"metrics.json",val)
        with (run/"summary.csv").open("w",encoding="utf-8-sig",newline="") as file:
            w=csv.DictWriter(file,fieldnames=["epoch","loss_mean","val_change_f1",
                                              "val_change_iou","val_pairs","val_subset_only"])
            w.writeheader()
            for line in log.read_text(encoding="utf-8").splitlines():
                rec=json.loads(line)
                w.writerow({k:rec.get(k) for k in w.fieldnames})
        print(f"[EPOCH COMPLETE] {epoch} train-loss={entry['loss_mean']:.4f} "
              f"val F1={f1:.4f} best F1={best_f1:.4f}",flush=True)
    print("[DONE] Best checkpoint:",best)
    return 0


