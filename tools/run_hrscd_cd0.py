"""CD0: shared SegFormer/MiT-B2 bi-temporal change detection + full land-cover heads.

Requires a FROZEN protocol generated by build_hrscd_cd0_protocol.py.
  python -m pip install torch transformers rasterio numpy pillow tqdm
  python tools/run_hrscd_cd0.py --stage train --protocol outputs/hrscd_cd0/hrscd_cd0_protocol.json \
    --run-dir outputs/hrscd_cd0/seed20260917 --pretrained nvidia/mit-b2 \
    --epochs 30 --batch-size 2 --crops-per-pair 16
  python tools/run_hrscd_cd0.py --stage validate --protocol outputs/hrscd_cd0/hrscd_cd0_protocol.json \
    --run-dir outputs/hrscd_cd0/seed20260917 --eval-max-pairs 0
No patches are split across train/val/test. Crops are sampled ON THE FLY from raw original full image pairs.
The official HRSCD has 0=no-info in land-cover; mask it from CE and coverage denominators.
Separate binary change label governs change detection even where T1/T2 classes agree.
"""
